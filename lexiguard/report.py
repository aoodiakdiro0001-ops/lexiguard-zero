# -*- coding: utf-8 -*-
"""Report rendering: Markdown, HTML, JSON — disclaimer in EVERY path.

Contract text stays local: rendering is pure string work on this machine.
Snippets are shortened and HTML-escaped; the document body is never
embedded in full in a report (share reports, not contracts).
"""
import html
import json

from . import __version__, DISCLAIMER_EN, DISCLAIMER_AR

_SEV_ICON = {"high": "🔴", "medium": "🟠", "low": "🟡", "info": "🔵"}
_SEV_ORDER = ("high", "medium", "low", "info")


def _disclaimer_block():
    return ("**Disclaimer / إخلاء مسؤولية:** %s / %s"
            % (DISCLAIMER_EN, DISCLAIMER_AR))


def to_json(result, remedies=None):
    data = result.as_dict()
    data["version"] = __version__
    data["disclaimer_en"] = DISCLAIMER_EN
    data["disclaimer_ar"] = DISCLAIMER_AR
    if remedies is not None:
        data["remedies"] = [r.as_dict() for r in remedies]
    return json.dumps(data, ensure_ascii=False, indent=2)


def to_markdown(result, remedies=None):
    d = result.document
    counts = result.counts()
    lines = []
    lines.append("# Lexi-Guard Zero — Contract Review / مراجعة عقد")
    lines.append("")
    lines.append(_disclaimer_block())
    lines.append("")
    lines.append("## Summary / الملخص")
    lines.append("")
    lines.append("| | |")
    lines.append("|---|---|")
    lines.append("| Document | `%s` |" % d.source)
    lines.append("| Extracted via | %s (%d chars, %d words%s) |" % (
        d.method, d.chars, d.words,
        ", %d pages" % d.pages if d.pages else ""))
    lines.append("| Risk band | **%s** — %s |" % (result.band.upper(),
                                                  result.band_en))
    lines.append("| Score | %d (high×5, medium×2, low×1) |" % result.score)
    lines.append("| Findings | %d high · %d medium · %d low · %d info |" % (
        counts["high"], counts["medium"], counts["low"], counts["info"]))
    if d.warnings:
        lines.append("| Extraction warnings | %s |"
                      % "; ".join(d.warnings))
    lines.append("")
    lines.append("> %s" % result.band_ar)
    lines.append("")
    if not result.findings:
        lines.append("No known clause patterns were detected. **This is "
                     "not a clearance** — the engine only knows the "
                     "patterns in its rule set, and unusual wording can "
                     "hide the same risk.")
        lines.append("")
        lines.append("لم تُكتشف أنماط بنود معروفة. **هذه ليست تصفية أو "
                     "ضمانة سلامة** — المحرّك يعرف أنماط قواعده فقط، "
                     "و الصياغات غير المعتادة قد تخفي نفس المخاطر.")
        lines.append("")
    if remedies:
        lines.append("## Counter-clause suggestions / بنود بديلة مقترحة")
        lines.append("")
        lines.append("Templates for YOU to adapt and have a lawyer check "
                     "— bracketed values like [30] must be filled in.")
        lines.append("")
        lines.append("قوالب لك أن تكيّفها ويراجعها محامٍ — القيم المعقوصة "
                     "مثل [30] تُملأ من قبلك.")
        lines.append("")
    by_rule = {}
    if remedies:
        for rem in remedies:
            by_rule.setdefault(rem.rule_id, []).append(rem)
    for sev in _SEV_ORDER:
        fs = [f for f in result.sorted_findings() if f.severity == sev]
        if not fs:
            continue
        lines.append("## %s %s (%d)" % (_SEV_ICON[sev], sev.upper(),
                                        len(fs)))
        lines.append("")
        for f in fs:
            r = f.rule
            lines.append("### %s — %s" % (r.id, r.title_en))
            lines.append("")
            lines.append("*%s* — %s" % (r.title_ar, f.location))
            lines.append("")
            lines.append("> %s" % f.snippet.replace("\n", " "))
            lines.append("")
            lines.append("- **Why it matters:** %s" % r.why_en)
            lines.append("- **لماذا يهم:** %s" % r.why_ar)
            for rem in by_rule.get(r.id, []):
                tag = (" (AI-rephrased draft)" if rem.source == "gemini"
                       else "")
                lines.append("- **Suggested counter-clause%s:** %s"
                             % (tag, rem.text_en))
                lines.append("- **البند البديل المقترح:** %s" % rem.text_ar)
            lines.append("")
    lines.append("---")
    lines.append("")
    lines.append(_disclaimer_block())
    lines.append("")
    lines.append("Generated by Lexi-Guard Zero %s · local review, no "
                 "upload." % __version__)
    return "\n".join(lines)


def to_html(result, remedies=None):
    md_like = to_markdown(result, remedies)   # build once, then escape
    parts = ['<!doctype html><html lang="en"><head><meta charset="utf-8">',
             '<meta name="viewport" content="width=device-width,'
             'initial-scale=1">',
             '<title>Lexi-Guard Zero — Review</title><style>',
             'body{font-family:system-ui,-apple-system,Segoe UI,Roboto,'
             'sans-serif;max-width:860px;margin:2rem auto;padding:0 1rem;'
             'line-height:1.55;color:#1a1a1a;background:#fafafa}',
             'pre{white-space:pre-wrap;word-break:break-word;background:'
             '#fff;border:1px solid #e2e2e2;border-radius:8px;padding:'
             '1.2rem}',
             '.band{display:inline-block;padding:.25rem .7rem;border-radius:'
             '999px;color:#fff;font-weight:600}',
             '.urgent{background:#c62828}.review{background:#ef6c00}',
             '.watch{background:#f9a825}.none{background:#546e7a}',
             '</style></head><body><pre>',
             html.escape(md_like),
             '</pre></body></html>']
    return "".join(parts)


def render(result, fmt="markdown", remedies=None):
    fmt = (fmt or "markdown").lower()
    if fmt in ("md", "markdown"):
        return to_markdown(result, remedies)
    if fmt == "html":
        return to_html(result, remedies)
    if fmt == "json":
        return to_json(result, remedies)
    raise ValueError("unknown format: %s (use markdown|html|json)" % fmt)
